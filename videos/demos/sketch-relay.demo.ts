type P = [number, number]
type S = P[]
interface Parts { parts: S[] }
type Stroke = S | Parts
interface Drawing { strokes: Stroke[]; wrong: [string, string] }

const rad = (d: number) => (d * Math.PI) / 180
/** Ellipse arc, degrees (0 = right, 90 = down). a1 < a0 runs anticlockwise. */
function E(cx: number, cy: number, rx: number, ry: number, a0 = 0, a1 = 360): S {
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / 10))
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = rad(a0 + ((a1 - a0) * i) / n)
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)] as P
  })
}
const C = (cx: number, cy: number, r: number, a0 = 0, a1 = 360) => E(cx, cy, r, r, a0, a1)
const R = (x: number, y: number, w: number, h: number): S => [[x, y], [x + w, y], [x + w, y + h], [x, y + h], [x, y]]
/** Sine wave from a to b. */
function W(a: P, b: P, amp: number, n: number): S {
  const [dx, dy] = [b[0] - a[0], b[1] - a[1]]
  const len = Math.hypot(dx, dy)
  const [nx, ny] = [-dy / len, dx / len]
  const k = Math.max(8, n * 10)
  return Array.from({ length: k + 1 }, (_, i) => {
    const t = i / k
    const o = amp * Math.sin(t * n * 2 * Math.PI)
    return [a[0] + dx * t + nx * o, a[1] + dy * t + ny * o] as P
  })
}
/** Zigzag from a to b with n teeth. */
function Z(a: P, b: P, amp: number, n: number): S {
  const [dx, dy] = [b[0] - a[0], b[1] - a[1]]
  const len = Math.hypot(dx, dy)
  const [nx, ny] = [-dy / len, dx / len]
  const out: S = [a]
  for (let i = 0; i < n; i++) {
    const t = (i + 0.5) / n
    out.push([a[0] + dx * t + nx * amp, a[1] + dy * t + ny * amp])
    out.push([a[0] + (dx * (i + 1)) / n, a[1] + (dy * (i + 1)) / n])
  }
  return out
}
function STAR(cx: number, cy: number, r1: number, r2: number, n: number, rot = -90): S {
  const out: S = []
  for (let i = 0; i <= n * 2; i++) {
    const r = i % 2 === 0 ? r1 : r2
    const a = rad(rot + (i * 180) / n)
    out.push([cx + r * Math.cos(a), cy + r * Math.sin(a)])
  }
  return out
}
/** Spiral out from the centre. */
function SP(cx: number, cy: number, r: number, turns: number, a0 = 0): S {
  const k = Math.ceil(turns * 36)
  return Array.from({ length: k + 1 }, (_, i) => {
    const t = i / k
    const a = rad(a0 + t * turns * 360)
    return [cx + r * t * Math.cos(a), cy + r * t * Math.sin(a)] as P
  })
}
