const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms))
const root = (p: Page) => p.getByTestId('sketch-relay')

async function phaseOf(p: Page): Promise<string | null> {
  return root(p).getAttribute('data-phase', { timeout: 2000 }).catch(() => null)
}

async function waitPhase(film: Film, phase: string, timeout = 30_000): Promise<void> {
  for (const n of NAMES) await expect(root(film.page(n))).toHaveAttribute('data-phase', phase, { timeout })
}

interface Roles { drawers: string[]; seer: string; rivals: string[] }
async function rolesOf(film: Film): Promise<Roles> {
  const out: Roles = { drawers: [], seer: '', rivals: [] }
  for (const n of NAMES) {
    const r = await root(film.page(n)).getAttribute('data-role')
    if (r === 'drawer') out.drawers.push(n)
    else if (r === 'seer') out.seer = n
    else out.rivals.push(n)
  }
  return out
}

/** The drawer holding the pen right now. */
async function whoseTurn(film: Film, drawers: string[], timeout = 15_000): Promise<string> {
  const until = Date.now() + timeout
  while (Date.now() < until) {
    for (const n of drawers) {
      const can = await film.page(n).getByTestId('sketch-canvas').getAttribute('data-can-draw', { timeout: 1000 }).catch(() => null)
      if (can === 'yes') return n
    }
    await sleep(60)
  }
  throw new Error(`nobody of ${drawers.join(', ')} has the pen`)
}

/** Points every `step` canvas units along the path (corners are smoothed by the canvas anyway). */
function resample(s: S, step: number): S {
  const out: S = [s[0]!]
  let carry = 0
  for (let i = 1; i < s.length; i++) {
    const [a, b] = [s[i - 1]!, s[i]!]
    const d = dist(a, b)
    let t = step - carry
    while (t <= d) {
      out.push([a[0] + ((b[0] - a[0]) * t) / d, a[1] + ((b[1] - a[1]) * t) / d])
      t += step
    }
    carry = d - (t - step)
  }
  const last = s[s.length - 1]!
  if (dist(out[out.length - 1]!, last) > 3) out.push(last)
  return out
}

const cdps = new Map<Page, CDPSession>()

/**
 * One real stroke with pointer events: press, drag, lift. The moves go out on
 * a steady clock over CDP without waiting for each one, because six recorded
 * phones make every awaited mouse.move take ~100 ms and the turn timer runs out.
 */
async function drawStroke(page: Page, pts: S, fast = false): Promise<void> {
  const canvas = page.getByTestId('sketch-canvas')
  await expect(canvas).toHaveAttribute('data-can-draw', 'yes')
  const box = (await canvas.boundingBox())!
  // Topsy-Turvy: this drawer's canvas is upside down, so the finger goes to the mirrored spot.
  const flipped = await canvas.evaluate((el) => el.classList.contains('rotate-180'))
  const at = ([x, y]: P): P => {
    const [u, v] = flipped ? [1000 - x, 1000 - y] : [x, y]
    return [box.x + (u / 1000) * box.width, box.y + (v / 1000) * box.height]
  }
  let cdp = cdps.get(page)
  if (!cdp) {
    cdp = await page.context().newCDPSession(page)
    cdps.set(page, cdp)
  }
  const send = (type: 'mouseMoved' | 'mousePressed' | 'mouseReleased', p: P, buttons: number) =>
    cdp.send('Input.dispatchMouseEvent', { type, x: at(p)[0], y: at(p)[1], button: 'left', buttons, clickCount: 1 })
  const path = resample(pts, fast ? 40 : 25)
  await send('mouseMoved', path[0]!, 0)
  await send('mousePressed', path[0]!, 1)
  const sent: Promise<unknown>[] = []
  for (const p of path.slice(1)) {
    await sleep(fast ? 15 : 45)
    sent.push(send('mouseMoved', p, 1))
  }
  await Promise.all(sent)
  await send('mouseReleased', path[path.length - 1]!, 0)
}

/** Whoever has the pen draws the next stroke. Returns their name. */
async function nextStroke(film: Film, drawers: string[], pts: S, opts: { fast?: boolean; focus?: boolean } = {}): Promise<string> {
  const who = await whoseTurn(film, drawers)
  if (opts.focus !== false) film.focus(who)
  await drawStroke(film.page(who), pts, opts.fast)
  return who
}

async function strokes(film: Film, drawers: string[], list: S[], gap = 450, fast = false): Promise<void> {
  for (const s of list) {
    await nextStroke(film, drawers, s, { fast })
    if (gap) await sleep(gap)
  }
}

async function guess(page: Page, text: string, typing = true): Promise<void> {
  const box = page.getByTestId('sr-guess')
  await box.click()
  if (typing) await box.pressSequentially(text, { delay: 70 })
  else await box.fill(text)
  await page.getByTestId('sr-guess-send').click()
}

/** Read the three prompt cards and choose one we can draw (the easy card always is). */
async function chooseOption(page: Page): Promise<{ index: number; prompt: string; drawing: Drawing }> {
  for (let i = 0; i < 3; i++) {
    const text = ((await page.getByTestId(`sr-option-${i}`).innerText()).split('\n')[0] ?? '').trim()
    if (DRAWINGS[text]) return { index: i, prompt: text, drawing: DRAWINGS[text]! }
  }
  throw new Error('no drawable prompt among the options')
}

/** The drawing, at most `max` strokes (details at the end are dropped first). */
function strokesFor(d: Drawing, max: number): S[] {
  return plan(d).slice(0, max)
}

async function toTop(film: Film): Promise<void> {
  for (const n of NAMES) await film.page(n).evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
}

/** Play a whole round quickly (inside a cut): pick, draw, the Seer gets it. */
async function quickRound(film: Film): Promise<void> {
  await waitPhase(film, 'pick')
  const r = await rolesOf(film)
  const picker = film.page(r.drawers[0]!)
  const o = await chooseOption(picker)
  await picker.getByTestId(`sr-option-${o.index}`).click()
  await waitPhase(film, 'draw')
  await toTop(film)
  await strokes(film, r.drawers, strokesFor(o.drawing, 8), 100, true)
  await sleep(1000)
  await guess(film.page(r.seer), o.prompt.toLowerCase(), false)
  await waitPhase(film, 'reveal')
}

