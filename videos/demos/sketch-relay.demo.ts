/** The teammate who "helps": a curly loop-de-loop stuck in the bottom-right corner. */
const WRECK: S = [[640, 960] as P, ...SP(830, 850, 110, 2, 180).reverse()]

const dist = (a: P, b: P) => Math.hypot(a[0] - b[0], a[1] - b[1])
const pathLen = (s: S) => s.slice(1).reduce((n, p, i) => n + dist(s[i]!, p), 0)
/** Ink per stroke is 1600 canvas units on the server; stay under it. */
const INK = 1450
function splitLong(s: S): S[] {
  const total = pathLen(s)
  if (total <= INK || s.length < 3) return [s]
  let acc = 0
  for (let i = 1; i < s.length; i++) {
    acc += dist(s[i - 1]!, s[i]!)
    if (acc >= total / 2) return [...splitLong(s.slice(0, i + 1)), ...splitLong(s.slice(i))]
  }
  return [s]
}
/** The strokes to draw, in order: touching parts joined, long lines split to fit the ink. */
function plan(d: Drawing): S[] {
  const out: S[] = []
  for (const st of d.strokes) {
    const parts = Array.isArray(st) ? [st] : st.parts
    let cur: S | null = null
    for (const p of parts) {
      if (cur && dist(cur[cur.length - 1]!, p[0]!) < 30) cur = [...cur, ...p]
      else {
        if (cur) out.push(cur)
        cur = [...p]
      }
    }
    if (cur) out.push(cur)
  }
  return out.flatMap(splitLong)
}


